"""
Level bank: dungeons generated by the Python DungeonGenerator, frozen into padded numpy arrays.

The JAX environment never generates levels; it only steps them. Keeping generation in Python
means generator parity is free, and the size of the bank directly sets how many distinct levels
an agent sees. This module depends only on numpy.
"""
import json

import numpy as np

from boltcrypt.envs.boltcrypt import BoltCrypt
from boltcrypt.envs.defines import Direction, PuzzleType, TILE_WALL

# Direction index order matches the action space: 0=N, 1=S, 2=E, 3=W
DIRECTIONS = (Direction.NORTH, Direction.SOUTH, Direction.EAST, Direction.WEST)
PUZZLE_CODES = {PuzzleType.NONE: 0, PuzzleType.BOULDER: 1, PuzzleType.BOULDER_PLATES: 2,
                PuzzleType.STONE: 3, PuzzleType.WARP_CYCLE: 4, PuzzleType.WARP_RND: 5}

MAX_SWITCHES = 4  # boulder puzzles use up to 3, mapped plates one per door
MAX_BOULDERS = 3
MAX_STONES = 3

BANK_VERSION = 1


def encode_level(env: BoltCrypt) -> dict:
    """Encode the level of a freshly reset BoltCrypt env (before any step) as unpadded arrays."""
    gen = env.generator
    m = gen.max_room_dim
    positions = sorted(gen.grid)
    index = {pos: i for i, pos in enumerate(positions)}
    n = len(positions)
    n_cand_max = (m - 2) ** 2

    lvl = {
        "seed": np.uint32(env.level_seed & 0xFFFFFFFF),
        "n_rooms": np.int32(n),
        "start_room": np.int32(index[gen.start_pos]),
        "key_room": np.int32(-1),
        "key_pos": np.full(2, -1, np.int8),
        "room_xy": np.zeros((n, 2), np.int32),
        "room_w": np.zeros(n, np.int8),
        "room_h": np.zeros(n, np.int8),
        "neighbor": np.full((n, 4), -1, np.int16),
        "door_off": np.full((n, 4), -1, np.int8),
        "grid": np.full((n, m, m), TILE_WALL, np.int8),
        "ptype": np.zeros(n, np.int8),
        "is_locked": np.zeros(n, bool),
        "is_trap": np.zeros(n, bool),
        "switches": np.full((n, MAX_SWITCHES, 2), -1, np.int8),
        "plate_dir": np.full((n, MAX_SWITCHES), -1, np.int8),
        "boulders0": np.full((n, MAX_BOULDERS, 2), -1, np.int8),
        "n_boulders": np.zeros(n, np.int8),
        "stones0": np.full((n, MAX_STONES, 2), -1, np.int8),
        "n_stones": np.zeros(n, np.int8),
        "cands": np.full((n, n_cand_max, 2), -1, np.int8),
        "n_cands": np.zeros(n, np.int16),
        "cand_index": np.full((n, m, m), -1, np.int16),
    }

    for i, pos in enumerate(positions):
        r = gen.grid[pos]
        if r.w > m or r.h > m:
            raise ValueError(f"room {pos} is {r.w}x{r.h}, larger than max_room_dim={m}")
        lvl["room_xy"][i] = pos
        lvl["room_w"][i], lvl["room_h"][i] = r.w, r.h
        lvl["grid"][i, :r.h, :r.w] = r.grid_array
        lvl["ptype"][i] = PUZZLE_CODES[r.puzzle_type]
        lvl["is_locked"][i] = r.is_locked
        lvl["is_trap"][i] = r.is_trap

        for d, off in r.doors.items():
            k = DIRECTIONS.index(d)
            lvl["neighbor"][i, k] = index[(pos[0] + d.value[0], pos[1] + d.value[1])]
            lvl["door_off"][i, k] = off

        if r.has_key:
            lvl["key_room"] = np.int32(i)
            lvl["key_pos"][:] = r.key_pos

        # Set order is irrelevant to the dynamics; sort so encodings are stable
        for j, sw in enumerate(sorted(r.switches)):
            lvl["switches"][i, j] = sw
            if sw in r.plate_door_map:
                lvl["plate_dir"][i, j] = DIRECTIONS.index(r.plate_door_map[sw])
        for j, b in enumerate(r.boulders):
            lvl["boulders0"][i, j] = b
        lvl["n_boulders"][i] = len(r.boulders)
        # Stone order matters: stones move sequentially and their index feeds step_noise
        for j, s in enumerate(r.stones):
            lvl["stones0"][i, j] = s
        lvl["n_stones"][i] = len(r.stones)

        # Warp keys were inserted in shuffled-candidate order; both warp modes index into it
        if r.warps:
            for j, c in enumerate(r.warps.keys()):
                lvl["cands"][i, j] = c
                lvl["cand_index"][i, c[0], c[1]] = j
            lvl["n_cands"][i] = len(r.warps)

    return lvl


def build_bank(generator_config: dict, seeds) -> dict:
    """Generate one level per seed and stack them, padding the room axis to the largest level."""
    env = BoltCrypt(generator_config=generator_config)
    levels = []
    for seed in seeds:
        env.reset(seed=int(seed))
        levels.append(encode_level(env))

    r_max = max(int(lvl["n_rooms"]) for lvl in levels)
    bank = {}
    for key, first in levels[0].items():
        if np.ndim(first) == 0 or key == "key_pos":
            bank[key] = np.stack([lvl[key] for lvl in levels])
            continue
        fill = False if first.dtype == bool else (TILE_WALL if key == "grid" else 0)
        if key in ("neighbor", "door_off", "switches", "plate_dir", "boulders0", "stones0",
                   "cands", "cand_index"):
            fill = -1
        padded = np.full((len(levels), r_max) + first.shape[1:], fill, first.dtype)
        for i, lvl in enumerate(levels):
            padded[i, :len(lvl[key])] = lvl[key]
        bank[key] = padded
    # Warp candidate lists only need to be as long as the largest warp room in the bank
    bank["cands"] = bank["cands"][:, :, :max(1, int(bank["n_cands"].max()))]
    bank["max_room_dim"] = np.int32(env.generator.max_room_dim)
    bank["config_json"] = np.array(json.dumps({"generator_config": generator_config,
                                               "bank_version": BANK_VERSION}))
    return bank


def save_bank(path, bank: dict):
    np.savez_compressed(path, **bank)


def load_bank(path) -> dict:
    with np.load(path) as f:
        bank = {k: f[k] for k in f.files}
    meta = json.loads(str(bank["config_json"]))
    if meta["bank_version"] != BANK_VERSION:
        raise ValueError(f"bank version {meta['bank_version']} != {BANK_VERSION}")
    return bank
